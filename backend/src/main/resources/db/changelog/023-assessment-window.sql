-- ================================================================
-- Экзаменационная сессия: где сдаётся аттестация и что впускает интервал
-- ================================================================
-- ЗАЧЕМ. Ограничение сегодня умеет только запрещать, поэтому чтобы поставить экзамен в сессию,
-- ячейку приходится освобождать — и одна логическая запись «сессия 12.01–28.01» рассыпается на
-- десятки пер-парных. Ломается Гант (он рисует полосами только целодневные), список и счётчик.
-- Экз. сессия по домену другая: жёсткая для всего, КРОМЕ аттестаций, которые в неё запланированы.
--
-- ДВЕ КОЛОНКИ, ДВА РАЗНЫХ ВОПРОСА — и правятся они в разных местах и с разным темпом.
--
--   curriculum_slot.assessment_window — НОРМА ПЛАНА: должна ли эта аттестация идти в сессию.
--       Правится в редакторе плана, один раз при заведении. Отсюда же считается потребность
--       сессии в днях (3 дня подготовки + экзамен; 1 день + зачёт) — подготовка непрерывна и
--       стоит непосредственно перед своей аттестацией.
--
--   kind_of_constraint.mode — ЧТО ВПУСКАЕТ ИНТЕРВАЛ у конкретной сущности. Правится диспетчером
--       по ходу раскладки, кистью в Ганте, и плана не касается.
--
-- ПОЧЕМУ НЕ ОДНОЙ КОЛОНКОЙ. Слот плана общий для всех групп курса (assignment связывает один слот
-- с несколькими потоками), поэтому маркером в плане нельзя сказать «у 951 этот зачёт в сессию,
-- у 953 — нет». А свободные дни принадлежат именно группе: экзамен принимает только лектор, групп
-- у него несколько, даты обязаны различаться — лектор идёт лесенкой, и у каждой группы своя дырка.
-- Обратно: одним лишь режимом интервала не выразить «этой аттестации нужны дни подготовки», без
-- чего не посчитать длину сессии и не отличить экзамен по физподготовке (сессии не требует).
--
-- ПОЧЕМУ НЕ ПОСЛАБЛЕНИЕ ПО ВИДУ ЗАНЯТИЯ. Экзамен и оба зачёта — одна категория ASSESSMENT, значит
-- «экзамены да, зачёты нет» категорией не выражается вовсе; а ветвление по конкретному виду
-- (KindOfStudy.EXAM) работало бы против уже принятого плана убрать такие ветвления.
--
-- Дата: 2026-08-12
-- ================================================================

-- --- 1. Норма плана: где сдаётся аттестация -----------------------------------------------
ALTER TABLE curriculum_slot
    ADD COLUMN assessment_window VARCHAR(20) NOT NULL DEFAULT 'STUDY_TIME';

COMMENT ON COLUMN curriculum_slot.assessment_window IS
    'Где сдаётся: SESSION — в экзаменационную сессию (нужны дни подготовки), STUDY_TIME — в учебное время.';

-- Дефолт STUDY_TIME описывает нынешнее ФАКТИЧЕСКОЕ поведение: генерация отфильтровывает только
-- EXAM (DistributionDiscipline), а зачёты раскладывает как рядовые занятия в семестр.
UPDATE curriculum_slot SET assessment_window = 'SESSION' WHERE kind_of_study = 'EXAM';

-- ⚠️ Экзамен по физической подготовке сессии и дней подготовки не требует — его слоты нужно
-- вернуть в STUDY_TIME вручную в редакторе плана. Автоматически их не отличить: признака
-- «дисциплина не требует подготовки» в модели нет, а угадывать по названию дисциплины — хуже,
-- чем оставить видимую задачу человеку.

-- --- 2. Режим интервала: что он впускает --------------------------------------------------
ALTER TABLE kind_of_constraint
    ADD COLUMN mode VARCHAR(30) NOT NULL DEFAULT 'BLOCKING';

COMMENT ON COLUMN kind_of_constraint.mode IS
    'BLOCKING — запрещает всё (как раньше); ASSESSMENT_WINDOW — впускает плановые аттестации сессии; '
        'ASSESSMENT_WINDOW_OPEN — впускает и внеплановые аттестации (свободные дни группы).';

UPDATE kind_of_constraint SET mode = 'ASSESSMENT_WINDOW' WHERE code = 'EXAM_SESSION';

