-- ================================================================
-- Сокращение учёной степени: слитно и без точек («ктн», а не «к.т.н.»)
-- ================================================================
-- ЗАЧЕМ. Правило «точки — часть формата, их расставляет форматтер» записано в комментариях
-- миграции 020. Решением заказчика от 2026-08-14 его больше нет: подпись собирается слитно,
-- потому что ровно так пишут документы, из которых мы читаем данные — в выгрузке сторонней
-- программы стоит «ктн», «кфмн», «двн». Одна конвенция на ввод и на вывод означает, что наша
-- подпись и подпись из чужого файла сравнимы напрямую, а не «на глаз».
--
-- ПОЧЕМУ ОТДЕЛЬНАЯ МИГРАЦИЯ РАДИ ТРЁХ КОММЕНТАРИЕВ. Править 020 нельзя: Liquibase считает
-- контрольную сумму по файлу целиком, и правка обвалит старт на базе, где миграция уже прошла.
-- Комментарий, описывающий несуществующее правило, вреднее отсутствующего — читающий сырой SQL
-- поверит ему.
--
-- ЗНАЧЕНИЯ СПРАВОЧНИКА ЭТА МИГРАЦИЯ НЕ ТРОГАЕТ. Разночтения вроде «воен» против «в» в
-- science_branch.short_name — это данные, и правит их пользователь в UI: перечень принадлежит
-- ему, а не релизу (docs/CONVENTIONS.md, «кто владеет списком значений»).
-- ================================================================

COMMENT ON TABLE science_branch IS 'Отрасли науки для учёной степени («технические» → ктн)';

COMMENT ON COLUMN science_branch.short_name IS
    'Буквенная часть сокращения степени без точек («т» → ктн, «фм» → кфмн)';

COMMENT ON COLUMN educator.science_branch_id IS
    'Отрасль науки степени; вместе с academic_degree даёт «ктн»';
