-- ================================================================
-- Фича 2 (Путь 2): сессия расписания привязана к учебному периоду
-- ================================================================
-- Чтобы можно было готовить расписание любого (в т.ч. будущего) семестра
-- независимо: «живое расписание», архивация и проекция становятся
-- per-period. Раньше сессия была глобальной (одна живая на всё).
--
-- Nullable — обратносовместимо: существующие сессии остаются с NULL
-- (легаси/глобальные). ON DELETE SET NULL — удаление периода не сносит
-- историю сессий.
-- ================================================================

ALTER TABLE schedule_session
    ADD COLUMN study_period_id INTEGER NULL REFERENCES study_period (id) ON DELETE SET NULL;

CREATE INDEX idx_session_period ON schedule_session(study_period_id);

COMMENT ON COLUMN schedule_session.study_period_id IS 'Учебный период сессии (Путь 2): живое расписание/архивация/проекция скоупятся по периоду. NULL = легаси/глобальная сессия';
