-- ================================================================
-- Принадлежность аудитории подразделению (кафедре)
-- ================================================================
-- Повод — импорт расписания: в шапке аудиторного файла кафедра напечатана прямо
-- («Загрузка учебной аудитории 252-3 … Факультет 9Ф … Кафедра: 91 кафедра»), и до сих пор импорт
-- эту строку выбрасывал. Решение И-16 («auditorium.org_unit_id для импорта не требуется») отменено
-- 2026-08-16: причина, которой тогда не было, названа — данные о владельце комнаты в выгрузке есть.
--
-- NULLABLE — по той же причине, что educator.org_unit_id и groups.org_unit_id (миграция 018):
-- у существующих комнат владельца нет, вывести его неоткуда, а придумать при миграции — записать
-- в базу неправду. «Кафедра не указана» — честное состояние, и подбор комнат его переживает:
-- предпочтение своей кафедре просто не срабатывает.
--
-- ON DELETE RESTRICT — четвёртая ссылка на org_unit и такая же, как три прежних. Комната не
-- производна от кафедры и обязана её пережить: расформирование кафедры не должно ни удалять
-- аудиторию, ни молча обезличивать её. Цена удаления называется заранее — счётчик комнат добавлен
-- в OrgUnitDeletionImpactDto рядом с преподавателями и группами; без него удаление кафедры с
-- комнатами отдало бы сырой 500 из БД.
--
-- Дата: 2026-08-16
-- ================================================================

ALTER TABLE auditorium
    ADD COLUMN org_unit_id INTEGER REFERENCES org_unit (id) ON DELETE RESTRICT;

CREATE INDEX idx_auditorium_org_unit_id ON auditorium (org_unit_id);

COMMENT ON COLUMN auditorium.org_unit_id IS 'Подразделение-владелец аудитории (кафедра). NULL = не указано; подбор комнат в этом случае предпочтения не даёт';
