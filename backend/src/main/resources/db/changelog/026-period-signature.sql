-- ================================================================
-- Подпись под расписанием: кто его подписывает
-- ================================================================
-- Повод — находка заказчика: в выгруженный бланк нечем добавить должность, регалии и фамилию с
-- инициалами руководителя, который расписание подписывает. Дописывали руками в каждом файле, а
-- файлов на ось выгрузки бывает сотня.
--
-- ПОЧЕМУ ТРИ СТРОКИ, А НЕ ССЫЛКА НА ПРЕПОДАВАТЕЛЯ (решение заказчика 2026-08-23). Соблазн был
-- очевиден: регалии уже смоделированы (миграция 020), подпись собирает EducatorTitles, оставалось
-- завести должность справочником. Но подписывает расписание не обязательно тот, кто в нём
-- преподаёт, — а заводить в справочник преподавателей человека, у которого нет ни одного занятия,
-- значит портить справочник ради одной строки в бланке. Свободный текст здесь честнее: он
-- описывает реквизит документа, а не сущность предметной области.
--
-- ПОЧЕМУ У ПЕРИОДА, А НЕ В НАСТРОЙКАХ ПРИЛОЖЕНИЯ. Подписант меняется от семестра к семестру, и это
-- данные, а не конфигурация: смена не должна требовать правки файла и перезапуска. Период —
-- ближайший владелец: выгрузка и так период-центрична (`?periodId=`), поэтому подпись едет вместе
-- с тем, что подписывают, и прошлые семестры сохраняют своего подписанта.
--
-- ПОЧЕМУ ТРИ КОЛОНКИ, А НЕ ОДНА СКЛЕЕННАЯ СТРОКА. Раскладка блока в бланке разная у частей:
-- должность идёт отдельной строкой, регалии и фамилия — одной. Склеенная строка заставила бы
-- бланк догадываться, где кончается должность.
--
-- Все три NULLABLE: подпись — необязательный реквизит, у прошлых периодов её взять неоткуда, а
-- пустая строка и «не заполнено» — одно и то же состояние (сервис приводит одно к другому).
-- Пусто во всех трёх = блока подписи в бланке нет; заполнена часть — печатается только она.
--
-- Дата: 2026-08-23
-- ================================================================

ALTER TABLE study_period
    ADD COLUMN signer_position    VARCHAR(255),
    ADD COLUMN signer_credentials VARCHAR(255),
    ADD COLUMN signer_name        VARCHAR(255);

COMMENT ON COLUMN study_period.signer_position IS 'Должность подписанта расписания («Начальник учебного отдела»); NULL/пусто — строка не печатается';
COMMENT ON COLUMN study_period.signer_credentials IS 'Регалии подписанта («полковник», «п-к, ктн, доц») — печатаются перед фамилией; NULL/пусто — не печатаются';
COMMENT ON COLUMN study_period.signer_name IS 'Фамилия и инициалы подписанта («Иванов И.И.»); NULL/пусто — не печатается, а если пусты все три поля, то и блока подписи нет';
