-- ================================================================
-- Организационная структура: подразделения (факультеты, кафедры, отделы)
-- ================================================================
-- Задача: преподаватели и группы должны знать своё подразделение. Кафедра может входить в
-- факультет, а может и не входить; преподаватель состоит в кафедре ИЛИ в отделе; группа
-- относится к кафедре или факультету. Глубина иерархии — произвольная (институт → факультет →
-- кафедра → …), решение заказчика от 2026-07-21.
--
-- ПОЧЕМУ ОДНА САМОССЫЛОЧНАЯ ТАБЛИЦА, А НЕ faculty/department/division ПО ОТДЕЛЬНОСТИ.
-- Отдельные таблицы потребовали бы на educator ДВЕ nullable FK (кафедра и отдел) с CHECK
-- «ровно одна не NULL», а на каждый новый вид подразделения — ещё колонку и правку всех
-- запросов. Это ровно тот выбор-по-типу, который в проекте уже числится долгом
-- (ResourceAvailabilityManager.getResource — цепочка instanceof). Здесь вместо этого:
-- одна строка на подразделение любого вида, одна FK у преподавателя, одна у группы,
-- новый вид подразделения = строка в справочнике org_unit_type, ноль изменений схемы.
--
-- ГДЕ ЖИВЁТ ПОЛИТИКА ВЛОЖЕННОСТИ. Правило «кто в ком может лежать» — в Java-enum
-- ru.enums.OrgUnitType через ранг (родитель строго «выше» ребёнка), проверяется чистой
-- функцией OrgUnitHierarchyRule. Схема этого не знает намеренно: правила вложенности
-- меняются чаще схемы, а FK всё равно не выразил бы ни ранг, ни запрет циклов.
-- Таблица org_unit_type нужна для ссылочной целостности и читаемости сырого SQL —
-- ровно как kind_of_study при enum KindOfStudy (labels там тоже продублированы осознанно).
--
-- УДАЛЕНИЕ — ВЕЗДЕ RESTRICT, БЕЗ КАСКАДОВ. Снос факультета не должен молча уносить кафедры,
-- а снос кафедры — преподавателей и группы. Цена удаления называется заранее
-- (/api/org-units/{id}/delete-impact), как уже сделано для аудитории, корпуса и локации.
-- Ср. с миграцией 017: там каскад был лекарством, потому что проекция ПРОИЗВОДНА от
-- размещения; здесь наоборот — преподаватель не производен от кафедры и обязан её пережить.
--
-- ССЫЛКИ У educator/groups — NULLABLE. Расставить 100+ существующих преподавателей и групп
-- миграцией нечем: соответствия в базе нет, оно появится вручную. «Без подразделения» —
-- легитимное состояние и полезный индикатор («не распределено: N»), а не дефект данных.
--
-- Дата: 2026-07-21
-- ================================================================

-- ---------------------------------------------------------------
-- Справочник видов подразделения (аналог kind_of_study при enum KindOfStudy)
-- ---------------------------------------------------------------
-- nesting_rank — «этаж» вида в иерархии: родитель допустим, если его ранг СТРОГО меньше
-- ранга ребёнка (институт 10 → факультет 20 → кафедра 30). Значения с шагом 10, чтобы новый
-- вид можно было вставить между существующими, не перенумеровывая остальные.
-- Колонка названа nesting_rank, а не rank: RANK — оконная функция PostgreSQL, и хотя как имя
-- колонки это допустимо, в сыром SQL читается двусмысленно.
-- ИСТОЧНИК ПРАВДЫ для политики — Java-enum OrgUnitType; здесь копия для FK и чтения глазами.
CREATE TABLE org_unit_type
(
    enum_name         VARCHAR(50)  PRIMARY KEY,
    full_name         VARCHAR(255) NOT NULL UNIQUE,
    abbreviation_name VARCHAR(50)  NOT NULL UNIQUE,
    nesting_rank      INTEGER      NOT NULL
);

INSERT INTO org_unit_type (enum_name, full_name, abbreviation_name, nesting_rank)
VALUES ('INSTITUTE',  'Институт', 'Ин-т', 10),
       ('FACULTY',    'Факультет', 'Ф-т', 20),
       ('DIVISION',   'Отдел',    'Отд.', 20),
       ('DEPARTMENT', 'Кафедра',  'Каф.', 30);

-- ---------------------------------------------------------------
-- Сами подразделения (Composite: узел и лист — одна и та же строка)
-- ---------------------------------------------------------------
CREATE TABLE org_unit
(
    id         SERIAL PRIMARY KEY,
    name       VARCHAR(255) NOT NULL,
    short_name VARCHAR(50),
    unit_type  VARCHAR(50)  NOT NULL REFERENCES org_unit_type (enum_name),
    parent_id  INTEGER      REFERENCES org_unit (id) ON DELETE RESTRICT,
    active     BOOLEAN      NOT NULL DEFAULT TRUE
);

-- Тёзки под разными родителями допустимы («Кафедра иностранных языков» на двух факультетах),
-- под одним — нет.
CREATE UNIQUE INDEX org_unit_name_in_parent_unique ON org_unit (parent_id, name);

-- Корни этим индексом НЕ покрыты: в PostgreSQL два NULL в UNIQUE считаются различными,
-- поэтому «Институт X» без родителя можно было бы завести дважды. Частичный индекс закрывает
-- ровно этот случай (NULLS NOT DISTINCT не используем — нужен PG 15+, а тут хватает индекса).
CREATE UNIQUE INDEX org_unit_root_name_unique ON org_unit (name) WHERE parent_id IS NULL;

CREATE INDEX idx_org_unit_parent ON org_unit (parent_id);
CREATE INDEX idx_org_unit_type ON org_unit (unit_type);

COMMENT ON TABLE org_unit IS 'Подразделение организации (факультет, кафедра, отдел…). Самоссылочное дерево произвольной глубины; вид — в org_unit_type, политика вложенности — в Java-enum OrgUnitType';
COMMENT ON COLUMN org_unit.parent_id IS 'Вышестоящее подразделение; NULL = верхний уровень (кафедра вне факультета — легитимный случай). RESTRICT: удаление родителя с детьми запрещено';
COMMENT ON COLUMN org_unit.active IS 'Действующее подразделение; расформированное скрывается из выбора, но остаётся ради исторических ссылок';
COMMENT ON COLUMN org_unit_type.nesting_rank IS 'Этаж вида в иерархии: родитель допустим, если его ранг строго меньше ранга ребёнка. Копия значения из Java-enum OrgUnitType';

-- ---------------------------------------------------------------
-- Принадлежность преподавателей и групп
-- ---------------------------------------------------------------
-- Ровно одно подразделение на преподавателя (решение заказчика: совместительство не моделируем).
-- Поэтому обычная FK, а не таблица членства.
ALTER TABLE educator
    ADD COLUMN org_unit_id INTEGER REFERENCES org_unit (id) ON DELETE RESTRICT;

ALTER TABLE groups
    ADD COLUMN org_unit_id INTEGER REFERENCES org_unit (id) ON DELETE RESTRICT;

CREATE INDEX idx_educator_org_unit ON educator (org_unit_id);
CREATE INDEX idx_group_org_unit ON groups (org_unit_id);

COMMENT ON COLUMN educator.org_unit_id IS 'Подразделение преподавателя (кафедра или отдел). NULL = ещё не распределён';
COMMENT ON COLUMN groups.org_unit_id IS 'Подразделение группы (кафедра или факультет). NULL = ещё не распределена';
