-- ================================================================
-- Запасной преподаватель назначения: числится за дисциплиной, но занятий не ведёт
-- ================================================================
-- Повод — требование заказчика (И-22, 2026-08-15): в подвале группового файла у дисциплины
-- перечислены преподаватели, и не все они ведут занятия. Часть числится «на страховку», на случай
-- отсутствия основного. Хранить такого человека надо, а его занятия в расписании — не учитывать.
--
-- ПОЧЕМУ ОТДЕЛЬНАЯ ТАБЛИЦА, А НЕ ФЛАГ В assignment_educators. По составу `educators` считается всё:
-- занятость ресурса при подборе места, нагрузка, сетка преподавателя, датчики качества, экспорт.
-- Флаг пришлось бы проверять в каждом из ~20 мест, где сегодня берётся состав, и первое же забытое
-- место сделало бы запасного занятым молча — с конфликтами там, где их нет. Отдельная связь
-- безопасна по построению: кто о ней не знает, тот её и не получит.
--
-- ЭТИМ ЖЕ ОБЪЯСНЯЕТСЯ АНОМАЛИЯ ЖИВОГО РАСПИСАНИЯ. Пока роли не разведены, запасной входит в состав
-- назначения наравне с ведущим — и в его сетке стоят занятия, которых он не ведёт, отчего он
-- «занят» в часы, когда свободен. Значит часть двойных бронирований (в живых данных их 179) — не
-- ошибка расписания, а ошибка модели. Проверяется числом: пересчитать на том же периоде.
--
-- ИНВАРИАНТ. Запасной не участвует в расписании — не занимает время, не попадает ни в свою сетку,
-- ни в нагрузку, ни в датчики. Но он участвует в АТРИБУЦИИ: печатается в подвале бланка группы
-- (колонки «Лектор» / «Другие виды занятий») после ведущих, без пометки — решение заказчика
-- 2026-08-24, уточняющее исходную формулировку И-22 «виден только в карточке назначения».
--
-- ПОЧЕМУ У ЗАПАСНОГО НЕТ ПРИЗНАКА «ЛЕКТОР/ПРАКТИК». Вид занятия задаёт назначение: assignment
-- висит на curriculum_slot, у которого есть kind_of_study. Запасной лекционного назначения идёт в
-- колонку «Лектор», любого нелекционного — в «Другие виды занятий». Третий признак дублировал бы
-- то, что уже известно из плана, и мог бы с ним разойтись.
--
-- ON DELETE: assignment_id каскадом (как в assignment_educators — снятие назначения уносит состав),
-- educator_id — RESTRICT: преподаватель, числящийся хоть где-то, молча не удаляется.
--
-- НЕ ПУТАТЬ со случаем «двое ведут вместе» (открытый вопрос 1a импорта): там оба ведущие, и оба
-- обязаны быть в assignment_educators — иначе занятие пропадёт из расписания одного из них.
--
-- Дата: 2026-08-24
-- ================================================================

CREATE TABLE assignment_reserve_educators
(
    assignment_id INTEGER NOT NULL REFERENCES assignment (id) ON DELETE CASCADE,
    educator_id   INTEGER NOT NULL REFERENCES educator (id) ON DELETE RESTRICT,
    PRIMARY KEY (assignment_id, educator_id)
);

COMMENT ON TABLE assignment_reserve_educators IS 'M:N: запасные преподаватели назначения — числятся за дисциплиной, но занятий не ведут. В расписании НЕ участвуют (ни занятости, ни нагрузки, ни сетки); печатаются только в подвале бланка группы после ведущих.';
COMMENT ON COLUMN assignment_reserve_educators.assignment_id IS 'Назначение, за которым числится запасной; удаление назначения уносит связь каскадом';
COMMENT ON COLUMN assignment_reserve_educators.educator_id IS 'Запасной преподаватель; RESTRICT — числящегося хоть где-то не удалить молча';
