-- ================================================================
-- Год набора учебной группы
-- ================================================================
-- Год, в котором группа поступила. Нужен, чтобы отличать одноимённые группы разных наборов
-- (одно и то же название переиспользуется из года в год) — в том числе при сверке справочников
-- на импорте расписания из сторонней программы.
--
-- NULLABLE — по той же причине, что и org_unit_id (миграция 018): у существующих групп года
-- набора нет, вывести его неоткуда (из названия он не следует), а придумывать значение при
-- миграции — значит записать в базу неправду. «Год не указан» — честное состояние.
--
-- CHECK — санитарная рамка от опечаток (202 вместо 2023, 20024 вместо 2024), а не доменное
-- правило: год набора вне 1900..2200 заведомо ошибка ввода.
--
-- Дата: 2026-07-21
-- ================================================================

ALTER TABLE groups
    ADD COLUMN enrollment_year INTEGER;

ALTER TABLE groups
    ADD CONSTRAINT groups_enrollment_year_sane
        CHECK (enrollment_year IS NULL OR enrollment_year BETWEEN 1900 AND 2200);

CREATE INDEX idx_group_enrollment_year ON groups (enrollment_year);

COMMENT ON COLUMN groups.enrollment_year IS 'Год набора (год поступления группы); NULL — не указан';
