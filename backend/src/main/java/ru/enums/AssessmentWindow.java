package ru.enums;

/**
 * Где сдаётся аттестация — норма учебного плана.
 *
 * <p>Enum, а не справочник: по значению ветвится код (генерация не размещает то, что уходит в
 * сессию, а датчик баланса считает по нему дни подготовки), значит перечнем владеет релиз, а не
 * пользователь. Правило — в docs/CONVENTIONS.md.</p>
 *
 * <p><b>Живёт на слоте плана</b> ({@code curriculum_slot}), а не на ограничении: «нужны ли этой
 * аттестации дни подготовки» — свойство дисциплины, а не интервала. Обратное — «что впускает вот
 * этот интервал у вот этой группы» — свойство ограничения, см. {@link ConstraintMode}.</p>
 */
public enum AssessmentWindow {

    /**
     * В экзаменационную сессию. Блок неразрывен и стоит непосредственно перед своей аттестацией:
     * 3 дня подготовки + экзамен, 1 день + зачёт. Генерация такие занятия не размещает — их
     * раскладывает диспетчер, потому что экзамен принимает лектор, и по группам он идёт лесенкой.
     */
    SESSION,

    /**
     * В учебное время, как обычное занятие. Дней подготовки не требует и в длину сессии не входит.
     * Сюда же относится экзамен по физической подготовке — единственный экзамен, которому сессия
     * не нужна.
     */
    STUDY_TIME
}
