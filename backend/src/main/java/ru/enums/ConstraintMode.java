package ru.enums;

/**
 * Что впускает интервал, закрытый ограничением.
 *
 * <p>Enum, а не пользовательское значение: по режиму ветвится проверка доступности, значит набор
 * принадлежит коду. Пользователь при этом свободно ВЫБИРАЕТ режим для своего вида ограничения —
 * ровно как он выбирает категорию вида занятия. Правило «кто владеет списком» — в
 * docs/CONVENTIONS.md; сами виды ограничений остаются пользовательским справочником.</p>
 *
 * <p><b>Одно поле, а не два флага:</b> «окно» и «окно, впускающее ещё и внеплановое» — состояния
 * одной оси, и парой булевых они дали бы невозможную комбинацию («впускает внеплановое, но не
 * является окном»).</p>
 */
public enum ConstraintMode {

    /**
     * Запрещает всё — поведение всех ограничений до появления этого признака и дефолт для новых
     * видов. Командировка, отпуск, наряд: занятие поверх такого интервала было и остаётся
     * конфликтом.
     */
    BLOCKING,

    /**
     * Окно промежуточной аттестации: впускает занятия, у которых слот плана помечен
     * {@link AssessmentWindow#SESSION}. Обычная «Экзаменационная сессия» — учебные занятия в неё
     * по-прежнему не проходят.
     */
    ASSESSMENT_WINDOW,

    /**
     * То же, плюс аттестации, которые планом в сессию не заводились. Это «свободные дни группы» —
     * дырка, образовавшаяся из-за лесенки лектора, куда диспетчер двигает обычный зачёт, освобождая
     * учебное время. Помечается точечно и на конкретную группу, поэтому вся сессия не открывается.
     */
    ASSESSMENT_WINDOW_OPEN
}
