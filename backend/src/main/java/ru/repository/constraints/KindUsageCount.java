package ru.repository.constraints;

/**
 * «Сколько ограничений размечено видом» — проекция для одного запроса вместо счётчика на строку.
 *
 * <p>Справочник показывает цену удаления у каждого вида. Наивно это считается тремя
 * {@code COUNT} на КАЖДЫЙ вид (девять видов — двадцать семь запросов на один GET); здесь три
 * запроса с {@code GROUP BY} на весь список, независимо от числа видов.</p>
 */
public interface KindUsageCount {

    String getCode();

    long getCount();
}
