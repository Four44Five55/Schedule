package ru.services.auditorium;

import ru.enums.TimeSlotPair;

import java.time.LocalDate;
import java.util.Set;
import java.util.UUID;

/**
 * Находка правила использования аудиторий — что не так с комнатой у конкретного занятия.
 *
 * <p><b>Находка сообщает факт, а не приговор.</b> «Тесно на 2 человека» и «комната занята» —
 * это наблюдения; блокировать, предупреждать или просто покрасить, решает тот, кто спрашивает.
 * Поэтому правило одинаково годится и датчику (сверка для дашборда), и будущему подбору
 * (фильтр), и интерфейсу выбора комнаты (статус в списке) — политика в них разная, факты одни.</p>
 *
 * <p>Одно занятие может дать <b>две</b> находки сразу (комната и занята, и мала). Схлопывать их
 * в одну, как это делает {@link ru.services.order.OrderViolation}, здесь нельзя: там находка
 * ведёт к одному действию («поправь порядок»), а тут причины независимы и чинятся по-разному.</p>
 *
 * @param placementId  занятие, к которому относится находка
 * @param auditoriumId комната, о которой речь
 * @param date         дата
 * @param slot         пара
 * @param kind         что именно не так
 * @param excess       на сколько человек не хватает мест; осмысленно для {@link Kind#OVER_CAPACITY},
 *                     для {@link Kind#DOUBLE_BOOKED} — 0
 * @param sharedWith   другие занятия в этой же комнате и ячейке; осмысленно для
 *                     {@link Kind#DOUBLE_BOOKED}, иначе пусто
 */
public record AuditoriumFinding(
        UUID placementId,
        Integer auditoriumId,
        LocalDate date,
        TimeSlotPair slot,
        Kind kind,
        int excess,
        Set<UUID> sharedWith
) {

    /**
     * Находка «у занятия нет комнаты вовсе».
     *
     * <p>Собирается <b>сборочным слоем</b>, а не {@link AuditoriumUsageRule}: правило отвечает на
     * вопросы об использовании комнаты, а тут комнаты нет — предъявить правилу нечего. Поэтому и
     * {@code auditoriumId} пуст, и {@code excess} равен нулю: ни того, ни другого не существует.</p>
     */
    public static AuditoriumFinding noAuditorium(UUID placementId, LocalDate date, TimeSlotPair slot) {
        return new AuditoriumFinding(placementId, null, date, slot, Kind.NO_AUDITORIUM, 0, Set.of());
    }

    /** Вид находки. Разные по природе: одна — про физику, вторая — про суждение. */
    public enum Kind {
        /**
         * Комната занята в этой ячейке другим занятием. Не бывает «допустимым»: две группы
         * не могут войти в одну дверь. Сейчас такое расписание система строит сама и не видит.
         */
        DOUBLE_BOOKED,
        /**
         * Поток не помещается в комнату ({@code excess} человек лишние). Не обязательно ошибка:
         * перебор на пару человек — нормальная рабочая ситуация, решать диспетчеру. Ошибка —
         * когда перебор в десятки.
         */
        OVER_CAPACITY,
        /**
         * У занятия нет комнаты вовсе.
         *
         * <p>Тоже про физику, но с другой причиной: занятие где-то идёт, а где — неизвестно.
         * Случается, когда комнату удалили (связь ушла каскадом) и когда расписание пришло
         * <b>импортом</b>: комната напечатана в файле, но у нас её нет либо одноимённых несколько.
         * Для импорта это не редкость, а массовое состояние.</p>
         *
         * <p>Собирается сборочным слоем, а не правилом, — см. {@link #noAuditorium}.</p>
         */
        NO_AUDITORIUM
    }
}
