package ru.services.reindex;

/**
 * Политика подбора комнат при пересортировке трека: какие аудитории у занятий после того, как
 * {@link TrackReorderStrategy} переставил темы по ячейкам.
 *
 * <p><b>Зачем отдельный контракт.</b> Порядок ячеек ({@code TrackReorderStrategy}) и подбор комнат
 * — разные ответственности (SRP) и, главное, точка расширения: сегодня достаточно самой дешёвой
 * политики, завтра для жёстких требований понадобится переподбор через {@code AuditoriumSelector}.
 * Шов вводится сразу, чтобы вторую стратегию можно было подключить, не трогая ни ядро сортировки,
 * ни сервис (OCP/DIP). Прецеденты enum-стратегий и чистых правил в проекте — {@code BoardAxis},
 * {@code LessonOrderRule}.</p>
 *
 * <p><b>Почему это вообще нужно.</b> Раньше пересортировка переносила размещение в другую ячейку
 * с его <i>прежней</i> комнатой, не проверяя занятость новой ячейки — 77 конфликтов из 179
 * возвращались после первого же переноса. Решение опирается на то, что перестановка биективна:
 * занятия класса стоят в разных ячейках, поэтому комната может столкнуться только с тем, кто в
 * класс не входит и не двигается. Значит проверка занятости делается в памяти, без workspace.</p>
 *
 * <p>Реализации — чистые функции: на вход {@link ReorderRoomContext}, на выход
 * {@link ReorderRoomPlan}. Ни Spring, ни БД.</p>
 */
public interface ReorderRoomResolver {

    /**
     * Подобрать комнаты занятиям после перестановки.
     *
     * @param context занятия класса + занятость не-классных размещений
     * @return комнаты по переехавшим размещениям + флаги неразрешённых жёстких требований
     */
    ReorderRoomPlan resolve(ReorderRoomContext context);
}
