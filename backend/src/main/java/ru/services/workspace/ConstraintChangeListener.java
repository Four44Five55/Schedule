package ru.services.workspace;

import jakarta.persistence.PostPersist;
import jakarta.persistence.PostRemove;
import jakarta.persistence.PostUpdate;

import java.util.concurrent.atomic.AtomicLong;

/**
 * Счётчик правок постоянных ограничений: «поколение ограничений».
 *
 * <p>Ограничения входят в снимок workspace (они превращаются в занятость ресурсов), но, в отличие
 * от размещений, <b>не поднимают версию сессии</b> — они вообще не привязаны к сессии, это
 * глобальные master-данные. Значит ключ {@code (sessionId, version)} их правок не замечает, и без
 * второго признака кэш показывал бы ячейку свободной после того, как её закрыли командировкой.</p>
 *
 * <p><b>Почему слушатель JPA, а не вызов из контроллеров.</b> Писателей у ограничений сегодня
 * шесть (три контроллера × создание/удаление), и запланированы bulk-эндпоинты для кисти и ластика.
 * Шесть напоминаний «не забудь сбросить кэш» — это шесть шансов забыть, причём молча: забытый сброс
 * даёт неверную подсветку без единой ошибки. Слушатель срабатывает на самой записи, поэтому новый
 * писатель прикрывается сам собой.</p>
 *
 * <p><b>Почему счётчик статический.</b> Слушателя создаёт JPA, а не Spring, и внедрять в него бины
 * — лишняя точка отказа на пути, который обязан работать всегда. Здесь это допустимо ровно потому,
 * что счётчик <b>монотонный и не контекстный</b>: писатель только увеличивает, читатель только
 * сравнивает. Лишний сброс безвреден (пересоберём снимок), «чужого значения» не существует — в
 * отличие от прежнего {@code CellForLessonFactory}, который хранил контекст запроса (какой сейчас
 * период) и потому отвечал неправильно, а не медленно.</p>
 *
 * <p>Срабатывает до коммита: откатившаяся транзакция тоже сбросит кэш. Это осознанный перекос в
 * сторону лишних пересборок.</p>
 */
public class ConstraintChangeListener {

    private static final AtomicLong GENERATION = new AtomicLong();

    /** Текущее поколение ограничений — часть ключа кэша workspace. */
    public static long generation() {
        return GENERATION.get();
    }

    @PostPersist
    @PostUpdate
    @PostRemove
    public void onConstraintChanged(Object constraint) {
        GENERATION.incrementAndGet();
    }
}
