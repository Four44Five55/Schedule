package ru.services.order;

import java.util.UUID;

/**
 * Находка правила порядка изучения — привязка занятия к предшествующей ему по плану лекции.
 *
 * <p><b>Это подсказка, а не запрет.</b> Расписание с находкой валидно по ресурсам; перенос и
 * установка никогда не блокируются (требование заказчика). Домен отдаёт только вид находки;
 * как её показывать — дело UI.</p>
 *
 * @param placementId        занятие, к которому относится находка
 * @param lecturePlacementId лекция-причина: последняя по плану лекция перед этим занятием
 * @param groupId            группа, в чьей дорожке находка видна (лекция и практика сопоставимы
 *                           только через общую группу)
 * @param kind               что именно не так
 * @param gapDays            календарных дней между лекцией и занятием; осмысленно для
 *                           {@link Kind#FAR_FROM_LECTURE}, для {@link Kind#BEFORE_LECTURE} — 0
 */
public record OrderViolation(
        UUID placementId,
        UUID lecturePlacementId,
        Integer groupId,
        Kind kind,
        int gapDays
) {

    /** Вид находки. Разные по смыслу и по силе: одна — ошибка, вторая — предупреждение. */
    public enum Kind {
        /** Занятие стоит РАНЬШЕ своей лекции — ошибка порядка изучения. */
        BEFORE_LECTURE,
        /** Занятие стоит слишком ДАЛЕКО после своей лекции (порог настраиваемый) — предупреждение. */
        FAR_FROM_LECTURE
    }
}
