package ru.services.importing;

import java.time.LocalDate;
import java.util.List;

/**
 * Итог сведения разрезов: сколько занятий получилось и чего им не хватает.
 *
 * <p><b>Цифры здесь отвечают на вопрос «хватает ли данных для записи».</b> Каждая строка — не
 * украшение отчёта, а конкретное препятствие следующего шага:</p>
 * <ul>
 *   <li>{@code withoutEducator} — такие занятия <b>не разрешаются в {@code Assignment}</b>: у
 *       дисциплины назначений несколько, по одному на преподавателя и состав потока, и без
 *       преподавателя выбрать не из чего (И-14);</li>
 *   <li>{@code withoutKind} — вид занятия есть только в групповом и аудиторном разрезах;
 *       без него не выбрать слот плана;</li>
 *   <li>{@code withoutTheme} — позиция слота берётся из номера темы (И-20); где темы нет,
 *       останется запасной путь «хронология внутри вида»;</li>
 *   <li>{@code missedByGroupCut} — датчик полноты из И-21: занятие видно у преподавателя или
 *       аудитории, а у группы стёрто маркером «ЭкзС» либо вышло за границы периода;</li>
 *   <li>{@code parallelSplit} — <b>разведённые параллельные занятия</b> (И-19): под одной
 *       дисциплиной в одно время шло несколько занятий, не связанных ни группой, ни комнатой, ни
 *       преподавателем. Не препятствие, а ответ на вопрос «сколько у нас полупотоков» — и защита от
 *       выдуманного потока: сложенные вместе, они требовали бы состава, которого не существует;</li>
 *   <li>{@code coTaught} — на занятии двое ведущих (открытый вопрос 1a): ведут вместе или один из
 *       них запасной (И-22). Разрешает человек, а не разбор.</li>
 * </ul>
 *
 * @param lessons          сведённых занятий
 * @param entries          строк-ячеек, из которых они сведены (во сколько раз больше — во столько
 *                         разрезы и повторяют друг друга)
 * @param seenInGroupCut   сколько занятий видит групповой разрез
 * @param seenInRoomCut    сколько видит аудиторный
 * @param seenInEducatorCut сколько видит преподавательский
 * @param missedByGroupCut сколько занятий групповой разрез потерял
 * @param withoutKind      без вида занятия
 * @param withoutTheme     без темы
 * @param withoutEducator  без преподавателя — не разрешатся в назначение
 * @param outsidePeriod    вне выбранного периода (размещать не будем, И-8)
 * @param undatedEntries   ячеек, у которых не восстановлена дата — в сведение не попали вовсе
 * @param parallelSplit    занятий, полученных разведением параллельных (полупотоки, И-19)
 * @param coTaught         занятий с двумя и более ведущими (вопрос 1a)
 * @param firstDate        первая дата сведённого расписания
 * @param lastDate         последняя
 * @param findings         находки, схлопнутые по тексту, с числом и файлом-образцом
 * @param sample           первые занятия «на глаз» — сверить с файлом, что сведено то самое
 */
public record MergeReport(
        int lessons,
        int entries,
        int seenInGroupCut,
        int seenInRoomCut,
        int seenInEducatorCut,
        int missedByGroupCut,
        int withoutKind,
        int withoutTheme,
        int withoutEducator,
        int outsidePeriod,
        int undatedEntries,
        int parallelSplit,
        int coTaught,
        LocalDate firstDate,
        LocalDate lastDate,
        List<Finding> findings,
        List<MergedLesson> sample
) {

    /**
     * Находка сведения: один текст, число повторов и файл-образец.
     *
     * <p>Схлопывание обязательно: одинаковая кривизна в трёхстах файлах это одна находка с числом,
     * а не триста строк, прячущих все остальные. Образец нужен, чтобы находку было чем проверить —
     * то же правило, что у замечаний разбора каталога.</p>
     */
    public record Finding(String message, int count, String example) {
    }
}
