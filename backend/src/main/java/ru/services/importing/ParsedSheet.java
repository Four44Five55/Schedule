package ru.services.importing;

import ru.enums.DayOfWeek;
import ru.enums.TimeSlotPair;

import java.time.LocalDate;
import java.util.List;

/**
 * Результат разбора одного файла чужой выгрузки: шапка, ячейки полотна и список замечаний.
 *
 * <p><b>Сырой уровень, без интерпретации.</b> Ячейка отдаётся списком строк как есть — что означает
 * каждая строка, зависит от разреза и решается слоем выше ({@link CutKind}). Разделение
 * намеренное: геометрия полотна у трёх разрезов одна и та же (проверено на живых файлах группы,
 * преподавателя и аудитории), а смысл строк — разный. Так разбор пишется один раз.</p>
 *
 * <p><b>Разбор тотален:</b> ни одна кривизна файла не бросает исключение. Всё, что не удалось
 * понять, попадает в {@link #problems()} — по тому же правилу, что и в
 * {@link GroupNumberDecoder}: первый прогон импорта заведомо кривой, и отчёт о кривизне ценнее
 * стектрейса.</p>
 *
 * @param source  имя файла, из которого этот разбор; {@code null} — источник не назван
 * @param header  шапка файла: чей разрез, факультет, кафедра, учебный год
 * @param cells   непустые ячейки полотна (пустые не выдаются вовсе)
 * @param footer  строки подвала — дисциплины с преподавателями; пусто у негрупповых разрезов
 * @param problems замечания разбора, по одному на находку
 */
public record ParsedSheet(
        String source,
        SheetHeader header,
        List<SheetCell> cells,
        List<DisciplineFooterParser.FooterRow> footer,
        List<String> problems
) {

    /** Имя источника для отчёта: файл мог приехать и без имени, но строка отчёта без него бесполезна. */
    public static final String UNNAMED = "(без имени)";

    /**
     * Тот же разбор, но с именем файла.
     *
     * <p>Имя приклеивается <b>после</b> разбора, а не протаскивается сквозь него: разбор — чистая
     * функция от содержимого, и знать, как называется файл на диске, ему незачем. А сверке —
     * наоборот: она сводит значения из полутора тысяч файлов, и «в базе нет» без указания источника
     * нечем проверить.</p>
     */
    public ParsedSheet withSource(String source) {
        return new ParsedSheet(source, header, cells, footer, problems);
    }

    /** Имя файла, никогда не {@code null} — для строк отчёта. */
    public String sourceName() {
        return source == null || source.isBlank() ? UNNAMED : source;
    }

    /** Какой разрез выгрузки перед нами. Определяется по тексту шапки. */
    public enum CutKind {
        /** «Расписание учебных занятий» + «Учебная группа 911». */
        GROUP,
        /** «Преподаватель: к-н Ветров Р.И. ктн». */
        EDUCATOR,
        /** «Загрузка учебной аудитории 252-3». */
        AUDITORIUM,
        /** Шапка не опознана — файл показывается списком, а не угадывается. */
        UNKNOWN
    }

    /**
     * Шапка файла.
     *
     * @param kind       разрез
     * @param owner      чьё это расписание: «911», «к-н Ветров Р.И. ктн», «252-3»
     * @param faculty    факультет из шапки: «9Ф»; {@code null}, если не указан
     * @param department кафедра из шапки: «91 кафедра»; {@code null} у группового файла
     * @param startYear  первый год учебного года: 2025 из «2025/2026 учебный год»
     * @param semester   «осенний» / «весенний»; {@code null}, если не указан
     */
    public record SheetHeader(
            CutKind kind,
            String owner,
            String faculty,
            String department,
            Integer startYear,
            String semester
    ) {
    }

    /**
     * Ячейка полотна: место во времени плюс её строки как есть.
     *
     * <p><b>Дата вычислена, а не прочитана номером недели.</b> В файле напечатано только число
     * месяца (строка «Даты» перед каждым днём), а порядковый номер недели в преподавательском
     * разрезе врёт — пустые недели вырезаны, нумерация при этом остаётся сплошной. Поэтому дата
     * восстанавливается по числу месяца и дню недели, а номер колонки сохраняется только для
     * диагностики.</p>
     *
     * @param day        день недели блока
     * @param slot       пара
     * @param weekColumn номер недельной колонки, 0-based — для сообщений, не для расчётов
     * @param date       восстановленная дата; {@code null}, если восстановить не удалось
     * @param lines      непустые строки ячейки в порядке файла
     * @param shaded     ячейка залита фоном (в живых файлах серым помечены недели маркеров)
     */
    public record SheetCell(
            DayOfWeek day,
            TimeSlotPair slot,
            int weekColumn,
            LocalDate date,
            List<String> lines,
            boolean shaded
    ) {
        /**
         * Маркер занятости, а не занятие: «ЭкзС», «Отп», «ЭПр».
         *
         * <p>Такие ячейки — это наши <b>постоянные ограничения</b>, а не занятия, и отличаются они
         * структурно: у занятия три строки (вид, дисциплина, место), у маркера одна. Смысловой
         * список кодов держать не нужно — он есть в самом файле, легендой «Другие обозначения».</p>
         */
        public boolean isMarker() {
            return lines.size() == 1;
        }
    }
}
