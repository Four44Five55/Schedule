package ru.services.importing;

import java.util.List;

/**
 * Ответ пробной загрузки: что понял разбор и чего из этого нет в нашей базе.
 *
 * <p><b>Две половины одного вопроса, поэтому один ответ.</b> Сводка по файлу говорит «что прочитано»
 * и считается без базы вовсе; сверка говорит «чего не хватает» и одна на всю пачку — дисциплина из
 * подвала одного файла встречается в ячейках другого. Разделить их на два запроса значило бы
 * заставить человека загружать одни и те же файлы дважды.</p>
 *
 * <p><b>Не пишется по-прежнему ничего</b> (решение И-10).</p>
 *
 * @param files    сводка по каждому файлу в порядке загрузки
 * @param matching сверка со справочниками по всей пачке
 */
public record ImportReport(
        List<SheetInspection> files,
        ImportMatchReport matching
) {
}
