package ru.services.importing;

import ru.enums.TimeSlotPair;
import ru.services.importing.ParsedSheet.CutKind;

import java.time.LocalDate;
import java.util.List;
import java.util.Set;

/**
 * Занятие, сведённое из всех разрезов, которые его видели.
 *
 * <p>Это ещё <b>не</b> наше занятие: ни одна строка не разрешена в сущность. Здесь только сведённый
 * факт «в такую дату, на такой паре, по такой дисциплине занимались такие группы у таких
 * преподавателей в таких комнатах» — то, из чего следующий шаг соберёт цепочку до
 * {@code Assignment}.</p>
 *
 * <p><b>Почему сведение вообще нужно.</b> Ни один разрез не полон: в преподавательской ячейке нет
 * вида занятия, в аудиторной — темы, в групповой — преподавателя, а часть занятий в групповом
 * разрезе стёрта маркером «ЭкзС» (И-21). Полная картина получается только объединением.</p>
 *
 * @param date          дата занятия
 * @param slot          пара
 * @param discipline    каноническое обозначение дисциплины ({@link DisciplineDictionary})
 * @param disciplineName полное название из подвала либо {@code null}
 * @param groups        группы, увиденные во всех файлах (потоковое занятие даёт несколько)
 * @param rooms         аудитории; несколько — занятие поделено по кабинетам (§9), и связь между
 *                      кабинетами подтверждена общей группой или общим преподавателем: иначе это
 *                      были бы разные занятия и сведение развело бы их
 * @param kind          вид занятия («Л», «ЛР»); {@code null} — не пришёл ни из одного разреза
 * @param theme         тема («Т.4»); есть только в групповом разрезе
 * @param educators     подписи преподавателей: из преподавательского разреза либо из подвала
 * @param cuts          разрезы, в которых занятие видно — по ним считается полнота
 * @param files         файлы, из которых оно сведено (первые несколько)
 * @param outsidePeriod дата вне выбранного периода: размещать не будем (И-8), но в план оно входит
 */
public record MergedLesson(
        LocalDate date,
        TimeSlotPair slot,
        String discipline,
        String disciplineName,
        List<String> groups,
        List<String> rooms,
        String kind,
        String theme,
        List<String> educators,
        Set<CutKind> cuts,
        List<String> files,
        boolean outsidePeriod
) {

    /** Видно только у преподавателя или аудитории — групповой разрез это занятие потерял (И-21). */
    public boolean missedByGroupCut() {
        return !cuts.contains(CutKind.GROUP);
    }

    /**
     * На занятии больше одного ведущего.
     *
     * <p>Параллельные занятия сюда <b>уже не попадают</b>: их разводит сведение по общей группе,
     * комнате или преподавателю ({@code ScheduleMerger.Cluster#split}). Значит эти двое связаны
     * общей комнатой или общей группой — то есть говорят об одном и том же занятии.</p>
     *
     * <p>Остаётся открытый вопрос 1a: ведут <b>вместе</b> (одно назначение, два преподавателя —
     * {@code assignment_educators} выражает прямо) или один из них запасной (И-22). По файлу это
     * неразличимо, поэтому число <b>показывается</b>, а не разрешается догадкой.</p>
     */
    public boolean coTaught() {
        return educators.size() > 1;
    }
}
