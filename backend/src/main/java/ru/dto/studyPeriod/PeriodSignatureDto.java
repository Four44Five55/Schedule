package ru.dto.studyPeriod;

/**
 * Подпись под расписанием периода: что печатать в блоке подписи бланка.
 *
 * <p>Отдельная команда, а не часть {@link StudyPeriodUpdateDto}: подпись правят из другого места и
 * по другому поводу (готовим выгрузку), чем даты и тип периода. Сложи их в одну форму — и правка
 * подписи потребовала бы прислать даты, которые править не собирались.</p>
 *
 * <p>Валидации нет намеренно: любая часть может быть пустой (подпись — необязательный реквизит),
 * а «правильность» должности или регалий — не наше знание. Пустое ФИО означает «блока подписи в
 * бланке нет».</p>
 *
 * @param signerPosition    должность: «Начальник учебного отдела»
 * @param signerCredentials регалии: «полковник», «п-к, ктн, доц» — печатаются перед фамилией
 * @param signerName        фамилия и инициалы: «Иванов И.И.»
 */
public record PeriodSignatureDto(
        String signerPosition,
        String signerCredentials,
        String signerName
) {}
