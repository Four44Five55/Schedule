package ru.dto.auditorium;

/**
 * Комната как вариант для конкретного занятия: что с ней сейчас и чем она грозит.
 *
 * <p><b>Отдаём ВСЕ комнаты, а не только годные.</b> Список «куда можно» отвечал бы на вопрос
 * системы, а диспетчеру нужен ответ на свой: почему нельзя вот в эту. «Занята лекцией 954» —
 * это информация, по которой он примет решение (перенести ту, поискать другую, махнуть рукой);
 * молчаливое отсутствие строки — не информация. Поэтому фильтрует не бэк, а глаз.</p>
 *
 * <p><b>Статус и теснота — разные поля, и это не случайно.</b> Занятость — физика: две группы не
 * войдут в одну дверь, поэтому {@link Status#BUSY} запрещает выбор. Теснота — суждение: перебор
 * на пару человек рабочий, на полсотни — фикция, поэтому она приходит <b>числом</b> и выбор не
 * запрещает. Решает человек (решение заказчика; в живой базе 134 занятия стоят с перебором ровно
 * на одного человека — жёсткий фильтр оставил бы их без комнаты).</p>
 *
 * @param auditoriumId комната
 * @param name         имя (для показа)
 * @param capacity     мест
 * @param status       можно ли выбрать и почему нет
 * @param shortfall    на сколько человек не хватит мест ({@code 0} — влезают все). Осмысленно при
 *                     любом статусе: тесная, но свободная комната остаётся выбираемой
 * @param occupiedBy   кто занял — для {@link Status#BUSY}; иначе {@code null}
 * @param current      уже назначена этому занятию (у занятия может быть несколько комнат:
 *                     экзамен с рассадкой, деление на полупотоки)
 */
public record AuditoriumOptionDto(
        Integer auditoriumId,
        String name,
        int capacity,
        Status status,
        int shortfall,
        String occupiedBy,
        boolean current
) {

    /** Почему комнату нельзя выбрать — или что её можно. */
    public enum Status {
        /** Свободна. Может быть тесной ({@code shortfall > 0}) — это не мешает выбрать. */
        FREE,
        /** Занята другим занятием в этой ячейке. Выбрать нельзя: физика. */
        BUSY,
        /** Закрыта постоянным ограничением (ремонт и т.п.) в этой ячейке. */
        CONSTRAINED
    }
}
