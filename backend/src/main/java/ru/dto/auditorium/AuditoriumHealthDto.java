package ru.dto.auditorium;

import java.util.List;
import java.util.UUID;

/**
 * Здоровье аудиторий в расписании периода: не стоят ли двое в одной комнате и все ли помещаются.
 *
 * <p><b>Зачем.</b> Оба состояния система создаёт сама и не показывает. Двойное бронирование
 * непредставимо в модели занятости решателя ({@code Map<ячейка, занятие>} — второй перезаписывает
 * первого), поэтому workspace слеп к нему по построению; строки {@code schedule_view} друг о друге
 * не знают, поэтому слеп и интерфейс. Расписание с конфликтами выглядит нормальным. Этот срез
 * превращает невидимое в число — как {@link ru.dto.ProjectionHealthDto} сделал с расхождением
 * Command/Query.</p>
 *
 * <p><b>Датчик, а не починка.</b> Ничего не исправляет и не блокирует. Он нужен раньше починки
 * подбора аудиторий по двум причинам: показать, что происходит на самом деле, и дать способ
 * проверить, что починка сработала («сделали — посмотрели на счётчик»). Чинить вслепую то, чего
 * не видно, — значит потом не знать, починил ли.</p>
 *
 * <p><b>Две метрики намеренно разной силы.</b> {@code doubleBooked} — про физику: две группы не
 * могут войти в одну дверь, допустимого значения тут нет, кроме нуля. {@code overCapacity} — про
 * суждение: перебор на пару человек рабочая ситуация, перебор в десятки — фикция. Поэтому
 * величина перебора отдаётся числом ({@code maxExcess} в разбивке), а не флагом: где граница,
 * решает диспетчер, а не система.</p>
 *
 * @param sessionId        живая сессия периода ({@code null} — сессии нет, проверять нечего)
 * @param placements       сколько занятий с комнатой проверено
 * @param conflictingCells всего ячеек, где комната занята больше чем одним занятием
 * @param doubleBooked     занятий, делящих комнату с кем-то ещё
 * @param overCapacity     занятий, не помещающихся в свою комнату
 * @param rooms            разбивка по комнатам, худшие первыми; чистые комнаты не попадают
 */
public record AuditoriumHealthDto(
        UUID sessionId,
        int placements,
        int conflictingCells,
        int doubleBooked,
        int overCapacity,
        List<RoomHealthDto> rooms
) {
}
