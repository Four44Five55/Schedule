package ru.dto.orgUnit;

import java.util.Set;

/**
 * Охват подразделения: кто в него попадает с учётом вложенности.
 *
 * <p>Это <b>вход для выборок</b>, а не отчёт: множества id ложатся в {@code IN (...)} фильтров
 * расписания по уже существующим индексам. Счётчики по ветке (сколько всего преподавателей на
 * факультете) выводятся отсюда размером множества — второй эндпоинт для них не нужен, а два
 * источника одного числа разошлись бы.</p>
 *
 * <p>Отдаются именно id, а не карточки: список преподавателей у фронта уже есть, и дублировать
 * их имена здесь значило бы завести ещё один денормализованный снимок, у которого нет мутатора,
 * объявляющего устаревание.</p>
 *
 * @param orgUnitId   корень охвата
 * @param name        его название (для заголовка фильтра)
 * @param unitIds     сам корень и все вложенные подразделения, на любую глубину
 * @param educatorIds преподаватели всех этих подразделений
 * @param groupIds    группы всех этих подразделений
 */
public record OrgUnitScopeDto(
        Integer orgUnitId,
        String name,
        Set<Integer> unitIds,
        Set<Integer> educatorIds,
        Set<Integer> groupIds
) {}
