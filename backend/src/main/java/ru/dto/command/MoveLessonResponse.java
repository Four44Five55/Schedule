package ru.dto.command;

import java.util.List;

/**
 * Ответ переноса занятия (или цепочки): сессия с актуальной версией + флаги пересортировки.
 *
 * <p><b>Почему одна команда, а не две.</b> Пересортировка трека в порядок плана — это часть
 * переноса, а не отдельное действие: перенесённое занятие «пузырьком» встаёт на своё плановое
 * место, соседи сдвигаются. Раньше фронт делал это вторым HTTP-запросом
 * ({@code POST /placements/{id}/reorder}), и получалось три беды:</p>
 * <ul>
 *   <li>бизнес-правило «после переноса пересортировать» жило на клиенте;</li>
 *   <li>между двумя транзакциями зияло окно, куда в многопользовательском режиме влезал конкурент —
 *       расписание успевало побывать в состоянии «перенесли, но не пересортировали»;</li>
 *   <li>сверить {@code expectedVersion} в {@code reorder} было невозможно: её только что сдвинул
 *       сам перенос, поэтому клиент заведомо приходил бы с «устаревшей» версией.</li>
 * </ul>
 * <p>Теперь это одна транзакция и одно поколение агрегата.</p>
 *
 * @param session  сессия-владелец с новой {@code version}
 * @param problems размещения, у которых пересортировка разорвала сцепку (предупреждение, не отказ)
 */
public record MoveLessonResponse(ScheduleSessionDto session, List<ReorderProblemDto> problems) {
}
