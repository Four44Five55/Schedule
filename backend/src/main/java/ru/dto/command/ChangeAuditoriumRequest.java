package ru.dto.command;

import java.util.Set;

/**
 * Запрос на смену аудитории у стоящего занятия.
 *
 * <p><b>Набор комнат, а не одна.</b> У занятия их может быть несколько, и по разным причинам:
 * экзамен с рассадкой по двум аудиториям, деление группы на полупотоки на английском, «возможны
 * ещё другие случаи». Вывести число автоматически нельзя — из вместимости следует только «не
 * влезли», а рассадка на экзамене к размеру группы отношения не имеет. Поэтому сколько комнат и
 * каких, называет человек; система проверяет только физику (комната свободна).</p>
 *
 * <p>Набор заменяет нынешние комнаты целиком, а не дополняет их: «сделать как здесь» проще и
 * предсказуемее, чем добавить/убрать по одной, и не требует от клиента знать текущее состояние.</p>
 *
 * <p><b>Почему это отдельная команда, а не поле в переносе.</b> В {@code MoveLessonRequest} есть
 * мёртвое поле {@code newAuditoriumIds} — фронт его шлёт, бэк игнорирует, — и его хочется
 * «оживить». Не стоит: смена комнаты и перенос по времени проверяются по-разному (перенос —
 * занятость всех участников в новой ячейке, смена — только комнаты в прежней) и вызываются в
 * разные моменты. Склеить их в один запрос — повторить историю {@code move}+{@code reorder},
 * которую в проекте уже расклеивали.</p>
 *
 * @param auditoriumIds новые комнаты занятия; пустой набор запрещён (занятию нужна хотя бы одна)
 * @param version       ожидаемая версия сессии (optimistic lock)
 */
public record ChangeAuditoriumRequest(
        Set<Integer> auditoriumIds,
        Long version
) {
}
