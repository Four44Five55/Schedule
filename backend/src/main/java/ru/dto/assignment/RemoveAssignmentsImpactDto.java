package ru.dto.assignment;

/**
 * Предпросмотр последствий снятия назначений: сколько назначений подпадает под критерий,
 * сколько среди них уже размещено в расписании и сколько из размещённых — закреплено.
 *
 * <p>Замки выделены отдельно, потому что теряются безвозвратно и бесшумно: размещения уносит
 * FK-каскад БД ({@code lesson_placement.assignment_id ON DELETE CASCADE}), а он про
 * {@code locked} ничего не знает. Ручная раскладка — самая дорогая работа пользователя,
 * поэтому её потеря должна быть названа до подтверждения.</p>
 *
 * @param matchedAssignments число назначений, удовлетворяющих критерию в охвате
 * @param placedLessons      число размещённых занятий (снесётся из расписания каскадом)
 * @param lockedLessons      сколько из них закреплено (замок) — потеряется ручная раскладка
 */
public record RemoveAssignmentsImpactDto(
        int matchedAssignments,
        long placedLessons,
        long lockedLessons
) {
}
