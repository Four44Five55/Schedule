package ru.dto.board;

import java.util.List;

/**
 * «Доска раскладки» ручной сборки расписания (Фича 2, Фаза B) — корень Composite-дерева
 * board → сущность → дисциплина → занятие с накопленными счётчиками на каждом уровне.
 *
 * <p>Заменяет прежнюю фронтовую реконструкцию из двух частичных источников (список неразмещённых +
 * проекция {@code schedule_view}). Строится на Command Side из полного набора назначений выбранных
 * курсов, поэтому:</p>
 * <ul>
 *   <li>показываются <b>все</b> сущности (в т.ч. с полностью сгенерированным расписанием);</li>
 *   <li>счётчики total/placed/unplaced честны на всех уровнях (roll-up);</li>
 *   <li>данные синхронны (без асинхронной проекции) и несут id сущностей + группы.</li>
 * </ul>
 *
 * <p><b>Заголовочные счётчики</b> считают <i>назначения</i> набора (каждое один раз), поэтому
 * total не зависит от оси и совпадает по смыслу с {@code /query/readiness}. Пер-сущностные счётчики
 * — в разрезе оси (общее лекции потока учитывается у каждой группы потока).</p>
 *
 * @param total    всего занятий к размещению (уникальных назначений выбранных курсов)
 * @param placed   из них размещено
 * @param unplaced из них в очереди
 * @param entities сущности (группы или преподаватели), отсортированы по имени
 */
public record PlacementBoardDto(
        int total,
        int placed,
        int unplaced,
        List<EntityPlacementDto> entities
) {
}
