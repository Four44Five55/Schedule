package ru.dto.board;

/**
 * Счётчик «распределено N/M» по одному преподавателю внутри курса — для раскрывающегося списка
 * во вкладке «Генерация», где генерацию и очистку можно запускать не только на всю дисциплину,
 * но и на отдельного преподавателя.
 *
 * <p>Единица счёта — назначение (в сессии ≤1 размещение на назначение), как и в
 * {@link CoursePlacementCountDto}. <b>Сумма по преподавателям может быть больше курсового
 * total:</b> совместное занятие (два преподавателя на одном назначении) учитывается у каждого —
 * это осознанно, охват «по преподавателю» в генерации/очистке работает так же.</p>
 *
 * @param educatorId   преподаватель
 * @param educatorName ФИО (для строки списка)
 * @param total        всего его назначений в курсе
 * @param placed       из них размещено в этой сессии
 */
public record EducatorPlacementCountDto(
        Integer educatorId,
        String educatorName,
        int total,
        int placed
) {}
