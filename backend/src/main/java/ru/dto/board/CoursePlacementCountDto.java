package ru.dto.board;

import java.util.List;

/**
 * Лёгкий счётчик размещённости курса в сессии — для индикатора «распределено N/M»
 * во вкладке генерации. Единица счёта — {@link ru.entity.Assignment} (в сессии ≤1
 * размещение на назначение), согласуется с заголовочными счётчиками доски раскладки.
 *
 * <p>{@code educators} — разбивка того же счёта по преподавателям курса: вкладка «Генерация»
 * разворачивает дисциплину в список преподавателей, на каждом из которых доступны те же
 * генерация и очистка, но уже в его охвате. Разбивку отдаёт бэк, потому что «всего занятий»
 * знает только он (полный набор назначений), а не Query Side.</p>
 *
 * @param courseId  курс (DisciplineCourse)
 * @param total     всего назначений курса (к раскладке)
 * @param placed    сколько из них уже размещено в этой сессии
 * @param educators разбивка по преподавателям (сумма может превышать {@code total} —
 *                  совместное занятие считается у каждого преподавателя)
 */
public record CoursePlacementCountDto(
        Integer courseId,
        int total,
        int placed,
        List<EducatorPlacementCountDto> educators
) {
}
