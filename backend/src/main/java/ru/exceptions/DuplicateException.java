package ru.exceptions;

/**
 * Такая строка уже есть: нарушено правило уникальности справочника.
 *
 * <p>Это <b>ожидаемый</b> ответ на ввод, а не сбой: пользователь завёл дисциплину с занятым
 * названием, аудиторию с занятым номером в том же корпусе, курс на уже занятый период. Дальше
 * человеку нужно поменять значение — и текст сообщения обязан назвать, какое именно.</p>
 *
 * <p><b>Не путать с {@link InUseException}:</b> здесь мешает существующая строка <i>впереди</i>
 * (завести нельзя), там — ссылки на строку <i>позади</i> (удалить нельзя). На уровне API оба
 * отображаются в {@code 409 Conflict}, но действия человеку требуются противоположные, поэтому
 * коды разные.</p>
 *
 * <p>⚠️ Проверка здесь — предварительная, а не замена ограничению БД: между проверкой и вставкой
 * есть гонка, и уникальность в конечном счёте держит {@code UNIQUE}. Смысл предварительной
 * проверки в том, чтобы обычный путь давал понятный текст, а не нарушение ограничения.</p>
 */
public class DuplicateException extends DomainException {

    public DuplicateException(String message) {
        super(message);
    }

    @Override
    public String code() {
        return "DUPLICATE";
    }
}
