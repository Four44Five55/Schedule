package ru.exceptions;

/**
 * Ввод разобран, но нарушает правило предметной области.
 *
 * <p>Отличие от Bean Validation ({@code @NotNull}, {@code @NotEmpty}) — в природе правила, а не в
 * его строгости. Аннотации проверяют <b>форму</b> запроса и не требуют знания о данных: пусто ли
 * поле, влезло ли число в диапазон. Сюда попадает то, что проверяется <b>только зная предметную
 * область и состояние базы</b>:</p>
 *
 * <ul>
 *   <li>«преподаватель не может быть на одном назначении и ведущим, и запасным» (И-22) — роли
 *       взаимоисключающие по смыслу, и ни одна аннотация об этом не знает;</li>
 *   <li>«нельзя сцепить слоты из разных учебных курсов»;</li>
 *   <li>«дата начала не может быть позже даты окончания»;</li>
 *   <li>спор о вложенности подразделений (кольцо, ранг вида).</li>
 * </ul>
 *
 * <p>Форму ловит {@code @Valid} и отвечает пофайловым разбором полей; правило ловит домен и
 * отвечает одной фразой, объясняющей <b>почему</b> нельзя. Смешивать их не нужно: разные проверки,
 * разные сообщения, разные места.</p>
 *
 * <p>⚠️ <b>Не для случаев, где нужны все причины сразу.</b> Исключение останавливается на первой, а
 * при валидации формы или разборе выгрузки человеку нужен полный список — там место
 * результату-объекту со списком замечаний (так устроен отчёт импорта), а не броску.</p>
 */
public class RuleViolationException extends DomainException {

    public RuleViolationException(String message) {
        super(message);
    }

    @Override
    public String code() {
        return "RULE_VIOLATION";
    }
}
