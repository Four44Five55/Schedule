package ru.exceptions;

import java.util.Map;

/**
 * Ожидаемый исход, а не сбой: ситуация, которую предметная область предусматривает и о которой
 * человеку надо рассказать своими словами.
 *
 * <p><b>Зачем отдельный корень.</b> До него доменные ошибки бросались типами
 * {@code IllegalStateException} и {@code IllegalArgumentException} — 61 бросок на весь проект. По
 * контракту JDK оба означают «вызывающий передал ерунду», то есть <b>дефект кода</b>, и потому
 * один и тот же тип нёс несовместимые вещи:</p>
 *
 * <pre>
 * IllegalStateException("Дисциплина с названием X уже существует")     ← ситуация, 409, для человека
 * IllegalStateException("Не удалось восстановить занятие для 42")      ← испорченное состояние, 500, в лог
 * </pre>
 *
 * <p>Разделить их обработчик не мог: поймает — и настоящие баги поедут пользователю как «вы ввели
 * не то»; не поймает — и живая ситуация улетит пятисоткой. Поэтому словарь заводится <b>раньше</b>
 * общего {@code @ControllerAdvice}, а не после него.</p>
 *
 * <h2>Что сюда попадает, а что нет</h2>
 * Наследник заводится тогда, когда исключение <b>есть кому поймать и осмысленно показать</b>. Если
 * ловить незачем — пусть остаётся {@code IllegalStateException} и летит в 500 вместе со стеком:
 * непредвиденный сбой обязан выглядеть как сбой, а не как замечание пользователю.
 *
 * <h2>Про HTTP тут не знают</h2>
 * Ни кода ответа, ни {@code ResponseStatusException}. Эти сервисы вызывает не только контроллер —
 * ещё импорт, планировщик и тесты, а код ответа принадлежит транспорту. Соответствие
 * «исключение → статус» живёт в одном месте на границе (шаг 2 —
 * {@code ProblemDetail}/RFC 9457).
 *
 * @see LessonMoveConflictException образец, с которого списан словарь: конфликт ресурсов переноса
 */
public abstract class DomainException extends RuntimeException {


    /**
     * Машинный код для клиента: {@code DUPLICATE}, {@code IN_USE}, {@code RULE_VIOLATION}…
     *
     * <p>Нужен, чтобы фронт мог ветвиться, <b>не разбирая русский текст</b>: сообщение пишется для
     * человека и переписывается свободно, а код — контракт. Ровно то же деление, что у видов
     * ограничений: код неизменен, название правится (см. {@code CONVENTIONS.md}).</p>
     */
    public abstract String code();

    /**
     * Дополнительные поля отказа для клиента — сверх {@code code} и текста.
     *
     * <p><b>Зачем метод на корне.</b> Число ссылок у {@link InUseException} граница сначала
     * доставала приведением к подтипу, и это была единственная трещина в открытости словаря:
     * статус нового наследника выводится умолчанием и правки не требует, а вот его собственное
     * поле потребовало бы второй такой строки — и так на каждого следующего. Здесь наследник
     * сам объявляет, что он умеет рассказать о себе, а граница только раскладывает.</p>
     *
     * <p>Имена ключей — часть контракта наравне с {@code code}: клиент читает их напрямую
     * ({@code usageCount} у {@code IN_USE}). Класть сюда то, что не адресовано клиенту, нельзя —
     * это тело ответа, а не журнал.</p>
     *
     * @return неизменяемая карта «имя поля → значение»; по умолчанию пусто
     */
    public Map<String, Object> details() {
        return Map.of();
    }

    protected DomainException(String message) {
        super(message);
    }

    protected DomainException(String message, Throwable cause) {
        super(message, cause);
    }
}
