package ru.exceptions;

/**
 * Названного объекта нет — и это ожидаемый исход, а не сбой.
 *
 * <p><b>Зачем свой тип вместо {@code jakarta.persistence.EntityNotFoundException}.</b> Тот
 * принадлежит <b>JPA</b>, и опираться на него означало бы, что доменное решение «такого объекта
 * нет» выражается словарём хранилища. Пока это было единственное осмысленное «не найдено» в
 * проекте, разница ничего не стоила; рядом со словарём {@link DomainException} она стала видна:
 * сервис не знает про HTTP — по той же причине он не должен знать и про JPA.</p>
 *
 * <p>Разница не только вкусовая. {@code EntityNotFoundException} <b>бросает и сам Hibernate</b> —
 * когда не разрешается ленивый прокси, то есть когда в базе битая ссылка. Это <b>дефект данных</b>,
 * ему место в пятисотке со стеком, а не в вежливом 404 для человека. Пока оба смысла ехали одним
 * типом, различить их на границе было нечем — ровно та же развилка, из-за которой заводился весь
 * словарь.</p>
 *
 * <p>Сюда попадает и то, что сущностью не является: несуществующий вид справочника из сегмента
 * пути, каталог выгрузки, которого нет. «Не найдено» — про адресуемый объект, а не про строку
 * таблицы.</p>
 */
public class NotFoundException extends DomainException {

    public NotFoundException(String message) {
        super(message);
    }

    @Override
    public String code() {
        return "NOT_FOUND";
    }
}
