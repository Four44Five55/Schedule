import type { ConstraintKindDto } from '../../types/api';
import type { KindCategory } from '../schedule/kindStyles';

/**
 * Считать ли занятие, стоящее поверх ограничения, конфликтом.
 *
 * Раньше конфликтом было ЛЮБОЕ совпадение «занятие + ограничение в одной ячейке». С появлением
 * окон промежуточной аттестации это перестало быть правдой: экзамен в экзаменационной сессии —
 * не ошибка, а единственное, ради чего сессия существует.
 *
 * ⚠️ Это НЕ копия бэкового правила, а его сознательно более грубая тень, и вот почему. Бэк решает
 * по норме плана (`curriculum_slot.assessment_window`: «эта аттестация запланирована в сессию»),
 * а в read-модели расписания этого поля нет — подразделение, регалии и прочие плановые признаки
 * в проекцию не денормализуют, пока у поля нет мутатора, объявляющего устаревание. Поэтому здесь
 * доступна только КАТЕГОРИЯ вида занятия.
 *
 * Расхождение ровно одно и оно узкое: экзамен по физподготовке (планом — в учебное время),
 * оказавшийся под окном сессии, бэк поставить не даст, а подсветка промолчит. В обратную сторону
 * ошибок нет: учебные занятия под любым окном по-прежнему краснеют, а любое занятие под жёстким
 * ограничением — тем более. Точная версия появится, когда `assessment_window` доедет до проекции
 * (см. FOLLOWUPS, раздел про экзаменационную сессию).
 *
 * @param kind     вид ограничения, занявшего ячейку (из справочника); неизвестен → считаем жёстким
 * @param category категория вида занятия, стоящего в ячейке
 */
export const isConstraintConflict = (
    kind: ConstraintKindDto | undefined,
    category: KindCategory | undefined,
): boolean => {
  // Вид не найден — данные разъехались (старая вкладка, погашенный вид). Строгость по умолчанию:
  // лучше показать лишний конфликт, чем спрятать настоящий.
  if (!kind || kind.mode === 'BLOCKING') return true;
  return category !== 'ASSESSMENT';
};
